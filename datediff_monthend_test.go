package datediff

import (
	"testing"
	"time"
)

// 验证 leapday 修复：月末生日不再多算 1 天，2/29 的 Feb 28 截断约定保留。
func TestBirthdayMonthEnd(t *testing.T) {
	d := &Datetime{}
	type tc struct {
		b, e  string
		y, m, dd int
	}
	cases := []tc{
		// 月末生日（非 2/29）：修复前多算 1 天，修复后应等于 Mar 1 约定
		{"2020-01-31", "2020-03-02", 0, 1, 0}, // 1/31+1mo=3/2 = e
		{"2020-01-31", "2020-03-03", 0, 1, 1}, // 3/2 + 1 day = 3/3
		{"2020-03-31", "2020-05-01", 0, 1, 0}, // 3/31+1mo=5/1 = e
		{"2020-03-31", "2020-05-02", 0, 1, 1},
		{"2020-05-31", "2020-07-01", 0, 1, 0}, // 5/31+1mo=7/1（6月只有30天，前向溢出）
		{"2020-07-31", "2020-08-31", 0, 1, 0}, // 7/31+1mo=8/31（8月有31天，不溢出）
		{"2020-08-31", "2020-10-01", 0, 1, 0}, // 8/31+1mo=10/1（9月30天）
		{"2020-10-31", "2020-12-01", 0, 1, 0}, // 10/31+1mo=12/1（11月30天）
		{"2020-12-31", "2021-01-31", 0, 1, 0}, // 12/31+1mo=1/31
		// 2/29 生日：保留 Feb 28 截断约定
		{"2000-02-29", "2001-03-01", 1, 0, 1}, // Feb 28 约定：1 周年 = 2/28，距 3/1 = 1 天
		{"2000-02-29", "2001-03-02", 1, 0, 2},
		{"2000-02-29", "2004-02-29", 4, 0, 0}, // 闰年同日
		{"2000-02-29", "2001-02-28", 0, 11, 30},
		{"2020-02-29", "2020-03-31", 0, 1, 2}, // 2/29+1mo=3/29（不溢出），3/29→3/31 = 2 天
		// 普通日期不变
		{"2000-01-01", "2001-01-01", 1, 0, 0},
		{"2000-01-01", "2001-02-02", 1, 1, 1},
	}
	for _, c := range cases {
		b, _ := time.Parse("2006-01-02", c.b)
		e, _ := time.Parse("2006-01-02", c.e)
		y, m, dd := d.Birthday(b, e)
		if y != c.y || m != c.m || dd != c.dd {
			t.Errorf("Birthday(%s,%s)=%d,%d,%d want %d,%d,%d",
				c.b, c.e, y, m, dd, c.y, c.m, c.dd)
		}
	}
}
